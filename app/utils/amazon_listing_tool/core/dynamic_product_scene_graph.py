    @staticmethod
    def _clamp_float(value: Any, low: float, high: float, default: float) -> float:
        try:
            v = float(value)
        except Exception:
            v = default
        return max(low, min(v, high))

    @staticmethod
    def _extract_json(text: str) -> Dict[str, Any]:
        text = (text or "").strip()
        text = re.sub(r"^```(?:json)?", "", text).strip()
        text = re.sub(r"```$", "", text).strip()
        start = text.find("{")
        end = text.rfind("}")
        if start >= 0 and end >= 0:
            text = text[start : end + 1]
        return json.loads(text)

    @staticmethod
    def _trim_transparent_padding(image: Image.Image) -> Image.Image:
        image = image.convert("RGBA")
        alpha = image.getchannel("A")
        bbox = alpha.getbbox()
        return image.crop(bbox) if bbox else image

    @staticmethod
    def _light_finish(image: Image.Image) -> Image.Image:
        rgb = image.convert("RGB")
        rgb = ImageEnhance.Contrast(rgb).enhance(1.03)
        rgb = ImageEnhance.Sharpness(rgb).enhance(1.02)
        return rgb.convert("RGBA")

    @staticmethod
    def _add_shadow(
        canvas: Image.Image,
        product_layer: Image.Image,
        x: int,
        y: int,
        shadow_strength: str = "medium",
    ) -> Image.Image:
        if shadow_strength == "soft":
            opacity, blur, offset = 65, 18, (8, 10)
        elif shadow_strength == "strong":
            opacity, blur, offset = 130, 26, (16, 20)
        else:
            opacity, blur, offset = 95, 22, (12, 15)

        alpha = product_layer.getchannel("A")
        shadow = Image.new("RGBA", product_layer.size, (0, 0, 0, opacity))
        shadow.putalpha(alpha)
        shadow = shadow.filter(ImageFilter.GaussianBlur(blur))

        shadow_canvas = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
        shadow_canvas.paste(shadow, (x + offset[0], y + offset[1]), shadow)
        return Image.alpha_composite(canvas, shadow_canvas)

    @staticmethod
    def _image_to_data_url(image_path: str) -> str:
        ext = Path(image_path).suffix.lower().replace(".", "")
        if ext == "jpg":
            ext = "jpeg"
        if ext not in {"png", "jpeg", "webp"}:
            ext = "png"
        with open(image_path, "rb") as f:
            b64 = base64.b64encode(f.read()).decode("utf-8")
        return f"data:image/{ext};base64,{b64}"

    @staticmethod
    def _save_b64_image(b64_json: str, output_path: str) -> str:
        Path(output_path).write_bytes(base64.b64decode(b64_json))
        return output_path

